def write_log(message):
    LOGS_DIR.mkdir(exist_ok=True)
    log_path = LOGS_DIR / "client_forms_log.txt"
    now = datetime.now().isoformat(timespec="seconds")
    with open(log_path, "a", encoding="utf-8") as f:
        f.write(f"[{now}] {message}\n")

def create_template_forms():
    TEMPLATES_DIR.mkdir(parents=True, exist_ok=True)

    written = []
    for filename, content in FORMS.items():
        path = TEMPLATES_DIR / filename
        with open(path, "w", encoding="utf-8") as f:
            f.write(content.strip() + "\n")
        written.append(path)

    return written

def copy_forms_to_case(case_id):
    case_dir = CASES_DIR / case_id
    if not case_dir.exists():
        raise FileNotFoundError(f"사건 폴더를 찾을 수 없습니다: {case_dir}")

    input_dir = case_dir / "00_input_forms"
    input_dir.mkdir(exist_ok=True)

    create_template_forms()

    copied = []
    for src in TEMPLATES_DIR.glob("*.md"):
        dst = input_dir / src.name
        shutil.copy2(src, dst)
        copied.append(dst)

    return copied

def main():
    parser = argparse.ArgumentParser(description="TaxCaseManager 고객 작성용 양도세 상담 서류 양식 생성기")
    parser.add_argument("--case-id", help="사건번호를 입력하면 해당 사건 폴더에도 양식을 복사")
    args = parser.parse_args()

    try:
        written = create_template_forms()
        print("[SUCCESS] 고객 작성용 기본 양식 생성 완료")
        print(f"[TEMPLATE_DIR] {TEMPLATES_DIR}")
        print(f"[COUNT] {len(written)}")

        for path in written:
            print(f"- {path.name}")

        if args.case_id:
            copied = copy_forms_to_case(args.case_id)
            print("")
            print("[SUCCESS] 사건 폴더 양식 복사 완료")
            print(f"[CASE_ID] {args.case_id}")
            print(f"[COUNT] {len(copied)}")
            for path in copied:
                print(f"- {path}")

        write_log(f"created_forms={len(written)} case_id={args.case_id or ''}")

    except Exception as e:
        write_log(f"ERROR {type(e).__name__}: {e}")
        print("[FAIL] 고객 작성용 양식 생성 실패")
        print(f"[ERROR] {type(e).__name__}: {e}")

if __name__ == "__main__":
    main()
